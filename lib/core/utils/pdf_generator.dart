import 'dart:typed_data';
import 'package:flutter/services.dart' show rootBundle;
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:intl/intl.dart';
import 'package:sanjay_roadlines_fleet/models/ticket_model.dart';
import 'package:sanjay_roadlines_fleet/models/loading_status_model.dart';
import 'package:sanjay_roadlines_fleet/models/unloading_status_model.dart';
import 'package:sanjay_roadlines_fleet/core/utils/detention.dart';

class PdfGenerator {
  // Chakka Saarthi brand colours (from the logo)
  static const PdfColor _ink = PdfColor.fromInt(0xFF14161F);
  static const PdfColor _road = PdfColor.fromInt(0xFF2A2E3B);
  static const PdfColor _yellow = PdfColor.fromInt(0xFFFFD23F);
  static const PdfColor _mist = PdfColor.fromInt(0xFFF4F4F0);

  // ---- Date helpers (all shown in Indian time, e.g. "29 Oct 2026, 10:34 PM") ----
  static DateTime _ist(DateTime d) => d.toUtc().add(const Duration(hours: 5, minutes: 30));
  static DateTime? _parse(dynamic v) {
    if (v is DateTime) return v;
    if (v is String && v.isNotEmpty) return DateTime.tryParse(v);
    return null;
  }
  /// Date and time, for moments (assigned, completed, loading time)
  static String _dateTime(dynamic v) {
    final d = _parse(v);
    return d == null ? 'N/A' : DateFormat('dd MMM yyyy, hh:mm a').format(_ist(d));
  }
  /// Date only, for days the driver picked (reporting, unloading)
  static String _dateOnly(dynamic v) {
    final d = _parse(v);
    return d == null ? 'N/A' : DateFormat('dd MMM yyyy').format(_ist(d));
  }
  /// Detention for one consolidated-report trip: worked out from its dates, else the saved value
  static int _tripDetention(Map<String, dynamic> t) {
    return calculateDetentionDays(_parse(t['reportingDate']), _parse(t['unloadingDate'])) ??
        (t['detentionDays'] as int?) ??
        0;
  }

  static Future<pw.MemoryImage?> _loadLogo() async {
    try {
      final data = await rootBundle.load('assets/images/chakka_saarthi_mark.png');
      return pw.MemoryImage(data.buffer.asUint8List());
    } catch (_) {
      return null;
    }
  }

  /// Every page: A4, room at the bottom, and a small "Generated by Chakka Saarthi" footer.
  static pw.PageTheme _pageTheme(pw.Font font) {
    return pw.PageTheme(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.fromLTRB(32, 32, 32, 52),
      buildForeground: (context) => pw.FullPage(
        ignoreMargins: true,
        child: pw.Align(
          alignment: pw.Alignment.bottomCenter,
          child: pw.Padding(
            padding: const pw.EdgeInsets.only(bottom: 18),
            child: pw.Column(
              mainAxisSize: pw.MainAxisSize.min,
              children: [
                pw.Container(width: 60, height: 1.5, color: _yellow),
                pw.SizedBox(height: 6),
                pw.Text(
                  'Generated by Chakka Saarthi  ·  Page ${context.pageNumber} of ${context.pagesCount}',
                  style: pw.TextStyle(font: font, fontSize: 8, color: PdfColors.grey600),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }

  /// Headline band: business name + report title on the left, logo on the right.
  static pw.Widget _brandHeader({
    required String businessName,
    required String title,
    required pw.MemoryImage? logo,
    required pw.Font font,
    required pw.Font boldFont,
    String? subtitle,
  }) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.fromLTRB(18, 16, 16, 16),
      decoration: const pw.BoxDecoration(
        color: _ink,
        borderRadius: pw.BorderRadius.all(pw.Radius.circular(6)),
      ),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.center,
        children: [
          pw.Expanded(
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  businessName,
                  style: pw.TextStyle(font: boldFont, color: PdfColors.white, fontSize: 20),
                ),
                pw.SizedBox(height: 4),
                pw.Text(
                  title,
                  style: pw.TextStyle(font: boldFont, color: _yellow, fontSize: 12, letterSpacing: 0.8),
                ),
                if (subtitle != null) ...[
                  pw.SizedBox(height: 3),
                  pw.Text(subtitle, style: pw.TextStyle(font: font, color: PdfColors.grey300, fontSize: 9)),
                ],
              ],
            ),
          ),
          if (logo != null) ...[
            pw.SizedBox(width: 12),
            pw.Image(logo, width: 46, height: 46),
          ],
        ],
      ),
    );
  }

  static Future<Uint8List> generateTripPdf({
    required TicketModel ticket,
    required LoadingStatusModel loading,
    required UnloadingStatusModel unloading,
    required String companyName,
  }) async {
    final pdf = pw.Document();
    final font = await PdfGoogleFonts.robotoRegular();
    final boldFont = await PdfGoogleFonts.robotoBold();
    final logo = await _loadLogo();
    final theme = _pageTheme(font);
    final now = DateTime.now().toUtc().add(const Duration(hours: 5, minutes: 30));
    final formattedNow = DateFormat('dd MMM yyyy, hh:mm a').format(now);

    pdf.addPage(
      pw.Page(
        pageTheme: theme,
        build: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              // HEADER BLOCK
              _brandHeader(
                businessName: companyName,
                title: 'TRIP COMPLETION REPORT',
                logo: logo,
                font: font,
                boldFont: boldFont,
              ),
              pw.SizedBox(height: 8),
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text('Trip ID: ${ticket.ticketId}', style: pw.TextStyle(font: font, fontSize: 10)),
                  pw.Text('Generated: $formattedNow', style: pw.TextStyle(font: font, fontSize: 10)),
                ],
              ),
              pw.SizedBox(height: 20),

              // SECTION A - Trip Details
              _buildSectionHeader('TRIP DETAILS', boldFont),
              _buildTable([
                ['Trip ID', ticket.ticketId],
                ['Assigned Date', ticket.formattedAssignedAt],
                ['Driver Name', loading.driverName],
                ['Vehicle Number', loading.vehicleNumber],
                ['Assigned By', ticket.createdBy],
              ], font, boldFont),
              pw.SizedBox(height: 20),

              // SECTION B - Loading Details
              _buildSectionHeader('LOADING DETAILS', boldFont),
              _buildTable([
                ['LR Number', loading.lrNumber],
                ['Journey From', loading.journeyFrom],
                ['Journey To', loading.journeyTo],
                ['Consignee', loading.consigneeName],
                ['Product', loading.product],
                ['Loading Weight (Kgs)', '${loading.loadingWeightKgs.toStringAsFixed(2)} Kgs'],
                ['Loading Date', _dateTime(loading.creationDate)],
              ], font, boldFont),
              pw.SizedBox(height: 20),

              // SECTION C - Unloading Details
              _buildSectionHeader('UNLOADING DETAILS', boldFont),
              _buildTable([
                ['Unloading Weight (Kgs)', '${unloading.unloadingWeightKgs.toStringAsFixed(2)} Kgs'],
                ['Unloading Date', _dateOnly(unloading.unloadingDate)],
                ['Shortage (Kgs)', '${unloading.shortageKgs.toStringAsFixed(2)} Kgs'],
              ], font, boldFont),
              pw.SizedBox(height: 20),

              // SECTION D - Reporting & Detention
              pw.Column(
                  children: [
                    _buildSectionHeader('REPORTING & DETENTION', boldFont),
                    _buildTable([
                      ['Reporting Date', _dateOnly(ticket.reportingDate)],
                      ['Unloading Date', _dateOnly(unloading.unloadingDate)],
                      [
                        'Detention Days',
                        '${calculateDetentionDays(ticket.reportingDate, unloading.unloadingDate) ?? ticket.detentionDays ?? 0} day(s)',
                      ],
                    ], font, boldFont),
                    pw.SizedBox(height: 20),
                  ],
                ),

              pw.Spacer(),
              pw.Center(
                child: pw.Text(
                  'This is a system-generated document.',
                  style: pw.TextStyle(font: font, fontSize: 8, color: PdfColors.grey, fontStyle: pw.FontStyle.italic),
                ),
              ),
            ],
          );
        },
      ),
    );

    return pdf.save();
  }

  // GENERATE CONSOLIDATED VEHICLE-WISE REPORT WITH FULL DETAILS
  static Future<Uint8List> generateConsolidatedReport({
    required String vehicleNumber,
    required List<Map<String, dynamic>> tripDetails,
    required String companyName,
    required DateTime fromDate,
    required DateTime toDate,
  }) async {
    final pdf = pw.Document();
    final font = await PdfGoogleFonts.robotoRegular();
    final boldFont = await PdfGoogleFonts.robotoBold();
    final logo = await _loadLogo();
    final theme = _pageTheme(font);
    final now = DateTime.now().toUtc().add(const Duration(hours: 5, minutes: 30));
    final formattedNow = DateFormat('dd MMM yyyy, hh:mm a').format(now);

    // Calculate totals
    double totalLoading = 0;
    double totalUnloading = 0;
    double totalShortage = 0;
    for (var trip in tripDetails) {
      totalLoading += (trip['loadingKgs'] as double?) ?? 0;
      totalUnloading += (trip['unloadingKgs'] as double?) ?? 0;
      totalShortage += (trip['shortageKgs'] as double?) ?? 0;
    }

    // COVER PAGE
    pdf.addPage(
      pw.Page(
        pageTheme: theme,
        build: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              _brandHeader(
                businessName: companyName,
                title: 'VEHICLE-WISE CONSOLIDATED REPORT',
                subtitle: 'Vehicle $vehicleNumber  ·  ${DateFormat('dd MMM yyyy').format(fromDate)} to ${DateFormat('dd MMM yyyy').format(toDate)}',
                logo: logo,
                font: font,
                boldFont: boldFont,
              ),
              pw.SizedBox(height: 30),
              _buildSectionHeader('REPORT SUMMARY', boldFont),
              _buildTable([
                ['Vehicle Number', vehicleNumber],
                ['Report Period', '${DateFormat('dd MMM yyyy').format(fromDate)} to ${DateFormat('dd MMM yyyy').format(toDate)}'],
                ['Total Trips', '${tripDetails.length}'],
                ['Total Loading (Kgs)', totalLoading.toStringAsFixed(2)],
                ['Total Unloading (Kgs)', totalUnloading.toStringAsFixed(2)],
                ['Total Shortage (Kgs)', totalShortage.toStringAsFixed(2)],
                ['Total Detention Days', '${tripDetails.fold<int>(0, (sum, t) => sum + _tripDetention(t))} day(s)'],
                ['Report Generated', formattedNow],
              ], font, boldFont),
            ],
          );
        },
      ),
    );

    // TRIP SUMMARY TABLE PAGE
    pdf.addPage(
      pw.Page(
        pageTheme: theme,
        build: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              _buildSectionHeader('TRIP SUMMARY TABLE', boldFont),
              pw.SizedBox(height: 10),
              pw.TableHelper.fromTextArray(
                headerStyle: pw.TextStyle(font: boldFont, fontSize: 9, color: _yellow),
                headerDecoration: const pw.BoxDecoration(color: _ink),
                cellStyle: pw.TextStyle(font: font, fontSize: 8),
                oddRowDecoration: const pw.BoxDecoration(color: _mist),
                cellAlignment: pw.Alignment.centerLeft,
                headerAlignment: pw.Alignment.centerLeft,
                cellHeight: 24,
                headers: ['#', 'Trip ID', 'Driver', 'Assigned', 'Completed', 'Loading (kg)', 'Unloading (kg)', 'Shortage (kg)', 'Detention'],
                data: tripDetails.asMap().entries.map((entry) {
                  final i = entry.key + 1;
                  final t = entry.value;
                  String assignedStr = '';
                  String completedStr = '';
                  try {
                    final assignedAt = t['assignedAt'] as String? ?? '';
                    if (assignedAt.isNotEmpty) {
                      final assignedDate = DateTime.tryParse(assignedAt);
                      if (assignedDate != null) {
                        final istDate = assignedDate.toUtc().add(const Duration(hours: 5, minutes: 30));
                        assignedStr = DateFormat('dd MMM yyyy').format(istDate);
                      } else {
                        assignedStr = assignedAt;
                      }
                    }
                  } catch (_) {
                    assignedStr = t['assignedAt'] as String? ?? '';
                  }
                  try {
                    final completedAt = t['completedAt'] as String? ?? '';
                    if (completedAt.isNotEmpty) {
                      final completedDate = DateTime.tryParse(completedAt);
                      if (completedDate != null) {
                        final istDate = completedDate.toUtc().add(const Duration(hours: 5, minutes: 30));
                        completedStr = DateFormat('dd MMM yyyy').format(istDate);
                      } else {
                        completedStr = completedAt;
                      }
                    }
                  } catch (_) {
                    completedStr = t['completedAt'] as String? ?? 'N/A';
                  }
                  return [
                    '$i',
                    (t['ticketId'] as String?) ?? '',
                    (t['driverName'] as String?) ?? (t['driverUserId'] as String?) ?? '',
                    assignedStr,
                    completedStr,
                    '${((t['loadingKgs'] as double?) ?? 0).toStringAsFixed(1)}',
                    '${((t['unloadingKgs'] as double?) ?? 0).toStringAsFixed(1)}',
                    '${((t['shortageKgs'] as double?) ?? 0).toStringAsFixed(1)}',
                    '${_tripDetention(t)} day(s)',
                  ];
                }).toList(),
              ),
            ],
          );
        },
      ),
    );

    // INDIVIDUAL TRIP DETAIL PAGES
    for (var i = 0; i < tripDetails.length; i++) {
      final trip = tripDetails[i];
      
      pdf.addPage(
        pw.Page(
          pageTheme: theme,
          build: (pw.Context context) {
            return pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                // Trip header
                pw.Container(
                  width: double.infinity,
                  padding: const pw.EdgeInsets.all(10),
                  decoration: const pw.BoxDecoration(
                    color: _road,
                    border: pw.Border(left: pw.BorderSide(color: _yellow, width: 4)),
                  ),
                  child: pw.Text(
                    'TRIP ${i + 1}: ${trip['ticketId']}',
                    style: pw.TextStyle(font: boldFont, color: PdfColors.white, fontSize: 14),
                  ),
                ),
                pw.SizedBox(height: 16),

                // Trip basic info
                _buildSectionHeader('TRIP DETAILS', boldFont),
                _buildTable([
                  ['Trip ID', trip['ticketId'] as String? ?? ''],
                  ['Vehicle', vehicleNumber],
                  ['Driver', trip['driverName'] as String? ?? trip['driverUserId'] as String? ?? ''],
                  ['Assigned By', trip['createdBy'] as String? ?? ''],
                  ['Assigned At', _dateTime(trip['assignedAt'])],
                  ['Completed At', _dateTime(trip['completedAt'])],
                ], font, boldFont),
                pw.SizedBox(height: 14),

                // Loading details
                _buildSectionHeader('LOADING DETAILS', boldFont),
                _buildTable([
                  ['LR Number', trip['lrNumber'] as String? ?? 'N/A'],
                  ['Journey From', trip['journeyFrom'] as String? ?? 'N/A'],
                  ['Journey To', trip['journeyTo'] as String? ?? 'N/A'],
                  ['Consignee', trip['consigneeName'] as String? ?? 'N/A'],
                  ['Product', trip['product'] as String? ?? 'N/A'],
                  ['Loading Weight (Kgs)', '${((trip['loadingKgs'] as double?) ?? 0).toStringAsFixed(2)} Kgs'],
                  ['Loading Date', _dateTime(trip['loadingDate'])],
                ], font, boldFont),
                pw.SizedBox(height: 14),

                // Unloading details
                _buildSectionHeader('UNLOADING DETAILS', boldFont),
                _buildTable([
                  ['Unloading Weight (Kgs)', '${((trip['unloadingKgs'] as double?) ?? 0).toStringAsFixed(2)} Kgs'],
                  ['Unloading Date', _dateOnly(trip['unloadingDate'])],
                  ['Shortage (Kgs)', '${((trip['shortageKgs'] as double?) ?? 0).toStringAsFixed(2)} Kgs'],
                ], font, boldFont),
                pw.SizedBox(height: 14),

                // Reporting & Detention
                pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      _buildSectionHeader('REPORTING & DETENTION', boldFont),
                      _buildTable([
                        ['Reporting Date', _dateOnly(trip['reportingDate'])],
                        ['Unloading Date', _dateOnly(trip['unloadingDate'])],
                        ['Detention Days', '${_tripDetention(trip)} day(s)'],
                      ], font, boldFont),
                    ],
                  ),
              ],
            );
          },
        ),
      );
    }

    // FINAL SUMMARY PAGE
    pdf.addPage(
      pw.Page(
        pageTheme: theme,
        build: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              _buildSectionHeader('CONSOLIDATED SUMMARY', boldFont),
              pw.SizedBox(height: 10),
              _buildTable([
                ['Vehicle Number', vehicleNumber],
                ['Report Period', '${DateFormat('dd MMM yyyy').format(fromDate)} to ${DateFormat('dd MMM yyyy').format(toDate)}'],
                ['Total Trips Completed', '${tripDetails.length}'],
                ['Total Loading (Kgs)', totalLoading.toStringAsFixed(2)],
                ['Total Unloading (Kgs)', totalUnloading.toStringAsFixed(2)],
                ['Total Shortage (Kgs)', totalShortage.toStringAsFixed(2)],
                ['Total Detention Days', '${tripDetails.fold<int>(0, (sum, t) => sum + _tripDetention(t))} day(s)'],
                ['Average Loading/Trip (Kgs)', tripDetails.isNotEmpty ? (totalLoading / tripDetails.length).toStringAsFixed(2) : '0.00'],
                ['Average Unloading/Trip (Kgs)', tripDetails.isNotEmpty ? (totalUnloading / tripDetails.length).toStringAsFixed(2) : '0.00'],
              ], font, boldFont),
              pw.SizedBox(height: 30),
              pw.Spacer(),
              pw.Center(
                child: pw.Text(
                  'This is a system-generated document. Generated on $formattedNow',
                  style: pw.TextStyle(font: font, fontSize: 8, color: PdfColors.grey, fontStyle: pw.FontStyle.italic),
                ),
              ),
            ],
          );
        },
      ),
    );

    return pdf.save();
  }

  static pw.Widget _buildSectionHeader(String title, pw.Font font) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 5),
      decoration: const pw.BoxDecoration(
        color: _road,
        border: pw.Border(left: pw.BorderSide(color: _yellow, width: 3)),
      ),
      child: pw.Text(
        title,
        style: pw.TextStyle(font: font, color: PdfColors.white, fontSize: 12),
      ),
    );
  }

  static pw.Widget _buildTable(List<List<String>> data, pw.Font font, pw.Font boldFont) {
    return pw.Column(
      children: data.asMap().entries.map((entry) {
        final index = entry.key;
        final row = entry.value;
        final isEven = index % 2 == 0;
        return pw.Container(
          decoration: pw.BoxDecoration(
            color: isEven ? _mist : PdfColors.white,
          ),
          padding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 6),
          child: pw.Row(
            children: [
              pw.Expanded(
                flex: 2,
                child: pw.Text(row[0], style: pw.TextStyle(font: boldFont, fontSize: 10)),
              ),
              pw.Expanded(
                flex: 3,
                child: pw.Text(row[1], style: pw.TextStyle(font: font, fontSize: 10)),
              ),
            ],
          ),
        );
      }).toList(),
    );
  }
}
