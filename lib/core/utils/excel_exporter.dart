import 'dart:io';
import 'package:excel/excel.dart';
import 'package:intl/intl.dart';
import 'package:path_provider/path_provider.dart';
import 'package:share_plus/share_plus.dart';
import 'package:sanjay_roadlines_fleet/core/utils/detention.dart';

/// Builds the vehicle-wise report as an Excel (.xlsx) file and opens the share sheet
/// (WhatsApp, Gmail, Drive, save to Files, …).
class ExcelExporter {
  static DateTime? _parse(dynamic v) =>
      v is DateTime ? v : (v is String && v.isNotEmpty ? DateTime.tryParse(v) : null);

  static String _dateTime(dynamic v) {
    final d = _parse(v);
    return d == null ? '' : DateFormat('dd MMM yyyy, hh:mm a').format(d.toUtc().add(const Duration(hours: 5, minutes: 30)));
  }

  static String _dateOnly(dynamic v) {
    final d = _parse(v);
    return d == null ? '' : DateFormat('dd MMM yyyy').format(d.toUtc().add(const Duration(hours: 5, minutes: 30)));
  }

  static double _num(dynamic v) => v is num ? v.toDouble() : 0;

  static Future<void> shareVehicleReport({
    required String businessName,
    required String vehicleNumber,
    required DateTime fromDate,
    required DateTime toDate,
    required List<Map<String, dynamic>> trips,
  }) async {
    final excel = Excel.createExcel();
    excel.rename('Sheet1', 'Trips');
    final sheet = excel['Trips'];
    final bold = CellStyle(bold: true);
    final period =
        '${DateFormat('dd MMM yyyy').format(fromDate)} to ${DateFormat('dd MMM yyyy').format(toDate)}';

    sheet.appendRow([TextCellValue(businessName)]);
    sheet.appendRow([TextCellValue('Vehicle-wise report · $vehicleNumber · $period')]);
    sheet.appendRow([TextCellValue('Generated by Chakka Saarthi on ${DateFormat('dd MMM yyyy, hh:mm a').format(DateTime.now())}')]);
    sheet.appendRow(<CellValue?>[]);
    sheet.cell(CellIndex.indexByString('A1')).cellStyle = bold;

    const headers = [
      'Trip ID', 'Driver', 'Assigned', 'Completed', 'LR Number', 'From', 'To', 'Consignee', 'Product',
      'Loading (kg)', 'Unloading (kg)', 'Shortage (kg)', 'Reporting Date', 'Unloading Date', 'Detention (days)',
    ];
    sheet.appendRow(headers.map((h) => TextCellValue(h)).toList());
    final headerRow = sheet.maxRows - 1;
    for (var c = 0; c < headers.length; c++) {
      sheet.cell(CellIndex.indexByColumnRow(columnIndex: c, rowIndex: headerRow)).cellStyle = bold;
    }

    double totalLoad = 0, totalUnload = 0, totalShort = 0;
    int totalDetention = 0;
    for (final t in trips) {
      final load = _num(t['loadingKgs']);
      final unload = _num(t['unloadingKgs']);
      final short = _num(t['shortageKgs']);
      final detention = calculateDetentionDays(_parse(t['reportingDate']), _parse(t['unloadingDate'])) ??
          (t['detentionDays'] as int?) ??
          0;
      totalLoad += load;
      totalUnload += unload;
      totalShort += short;
      totalDetention += detention;
      sheet.appendRow([
        TextCellValue((t['ticketId'] ?? '').toString()),
        TextCellValue((t['driverName'] ?? t['driverUserId'] ?? '').toString()),
        TextCellValue(_dateTime(t['assignedAt'])),
        TextCellValue(_dateTime(t['completedAt'])),
        TextCellValue((t['lrNumber'] ?? '').toString()),
        TextCellValue((t['journeyFrom'] ?? '').toString()),
        TextCellValue((t['journeyTo'] ?? '').toString()),
        TextCellValue((t['consigneeName'] ?? '').toString()),
        TextCellValue((t['product'] ?? '').toString()),
        DoubleCellValue(load),
        DoubleCellValue(unload),
        DoubleCellValue(short),
        TextCellValue(_dateOnly(t['reportingDate'])),
        TextCellValue(_dateOnly(t['unloadingDate'])),
        IntCellValue(detention),
      ]);
    }

    sheet.appendRow([
      TextCellValue('TOTAL (${trips.length} trips)'),
      null, null, null, null, null, null, null, null,
      DoubleCellValue(totalLoad),
      DoubleCellValue(totalUnload),
      DoubleCellValue(totalShort),
      null, null,
      IntCellValue(totalDetention),
    ]);
    final totalRow = sheet.maxRows - 1;
    for (var c = 0; c < headers.length; c++) {
      sheet.cell(CellIndex.indexByColumnRow(columnIndex: c, rowIndex: totalRow)).cellStyle = bold;
    }
    for (var c = 0; c < headers.length; c++) {
      sheet.setColumnWidth(c, c == 0 ? 20 : (c == 1 || c == 7 ? 22 : 16));
    }

    final bytes = excel.save();
    if (bytes == null) throw Exception('Could not create the Excel file');

    final dir = await getTemporaryDirectory();
    final safeVehicle = vehicleNumber.replaceAll(RegExp(r'[^A-Za-z0-9]'), '');
    final file = File('${dir.path}/Report_${safeVehicle}_${DateFormat('ddMMMyyyy').format(fromDate)}-${DateFormat('ddMMMyyyy').format(toDate)}.xlsx');
    await file.writeAsBytes(bytes, flush: true);

    await Share.shareXFiles(
      [XFile(file.path, mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet')],
      subject: '$businessName – $vehicleNumber report',
      text: '$businessName – vehicle report for $vehicleNumber ($period)',
    );
  }
}
